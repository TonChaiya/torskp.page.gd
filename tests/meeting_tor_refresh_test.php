<?php
declare(strict_types=1);
require __DIR__ . '/../core/meeting_tor_refresh.php';
$n = 0;
function check(bool $ok, string $name): void { global $n; if (!$ok) throw new RuntimeException($name); ++$n; }
$row = ['name'=>'Fixture drug', 'unit'=>'tablet','specification'=>"1. fixture\n2. second",'quantity'=>2,'reference_price'=>1.25,'offer_price'=>1.1,'offer_total'=>2.2];
$rows = [$row];
$history = ['id'=>9,'case_id'=>3,'items_json'=>json_encode($rows)];
check(meetingTorUsableItems($rows), 'valid rows');
check(!meetingTorUsableItems([]), 'empty');
check(!meetingTorUsableItems(['row'=>$row]), 'not list');
check(!meetingTorUsableItems([false]), 'non-array row');
check(!meetingTorUsableItems([array_diff_key($row,['specification'=>true])]), 'missing specification');
check(!meetingTorUsableItems([array_replace($row,['offer_price'=>'invalid'])]), 'non-numeric price');
check(!meetingTorUsableItems([array_replace($row,['offer_price'=>INF])]), 'nonfinite price');
check(meetingTorRefreshItems($history,3)===$rows,'same-case refresh');
check(meetingTorRefreshItems($history,4)===null,'cross-case blocked');
check(meetingTorRefreshItems(array_replace($history,['case_id'=>null]),3)===null,'unlinked history blocked');
check(meetingTorRefreshItems(array_replace($history,['items_json'=>'{invalid']),3)===null,'invalid JSON');
check(meetingTorRefreshItems(null,3)===null,'missing history');
$a=meetingTorFingerprint(3,9,'tor',$rows,9);
check($a===meetingTorFingerprint(3,9,'tor',$rows,9),'deterministic hash');
check($a!==meetingTorFingerprint(3,9,'tor',[array_replace($row,['offer_price'=>2])],9),'changed price');
check($a!==meetingTorFingerprint(3,9,'tor',$rows,10),'changed linked history');
check($a!==meetingTorFingerprint(3,9,'saved',$rows),'changed source');
check($a!==meetingTorFingerprint(4,9,'tor',$rows,9),'changed case');
check(meetingTorUpdateCount('จัดหาการจัดซื้อยา จำนวน ๑ รายการ', '๒')==='จัดหาการจัดซื้อยา จำนวน ๒ รายการ','standard count');
check(meetingTorUpdateCount('จัดซื้อยา จำนวน 1 รายการ ราคา 100 บาท [medicine_items]', '๒')==='จัดซื้อยา จำนวน ๒ รายการ ราคา 100 บาท [medicine_items]','preserve price and marker');
check(meetingTorUpdateCount('จำนวน ๓ คน ราคา 100 บาท', '๒')==='จำนวน ๓ คน ราคา 100 บาท','preserve unrelated text');
check(meetingTorPriceBasis('saved', [], ['price_basis'=>'reference'], 9)==='offer', 'legacy meeting preserves offer');
check(meetingTorPriceBasis('saved', ['price_basis'=>'reference'], ['price_basis'=>'offer'], 9)==='reference', 'saved reference basis frozen');
check(meetingTorPriceBasis('tor', [], ['history_id'=>9,'price_basis'=>'reference'], 9)==='reference', 'refresh reference mode');
check(meetingTorPriceBasis('tor', [], ['history_id'=>9,'price_basis'=>'offer'], 9)==='offer', 'refresh offer mode');
check(meetingTorPriceBasis('tor', [], ['history_id'=>9], 9)==='reference', 'TOR default reference');
check(meetingTorPriceBasis('tor', [], ['history_id'=>10,'price_basis'=>'reference'], 9)==='offer', 'other history does not borrow basis');
check(meetingTorUnitPrice($row,'reference')===1.25 && meetingTorUnitPrice($row,'offer')===1.1, 'unit price selection');
check(meetingTorReferenceTotal($row)===2.5, 'reference total ordinary');
check(meetingTorReferenceTotal(array_replace($row,['quantity'=>3,'package_size'=>10,'package_count'=>3,'requested_quantity'=>30,'reference_price'=>35]))===105.0, 'reference total package, not requested units');
check(meetingTorFingerprint(3,9,'tor',$rows,9,'reference')!==meetingTorFingerprint(3,9,'tor',$rows,9,'offer'),'basis-only stale check');
echo "PASS $n checks\n";
